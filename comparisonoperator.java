public class comparisonoperator {
    public static void main(String[] args) {
        int number1 = 20;
        int number2 = 20;

        boolean result;
        result = (number1 == number2);
        System.out.println(result);
        //!=
        result = (number1 != number2);
        System.out.println(result);
        //<> <= >=
        result = (number1 < number2);
        System.out.println(result);
    } 

}