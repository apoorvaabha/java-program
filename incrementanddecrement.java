public class incrementanddecrement {
    public static void main(String[] args) {
        int x = 50;
        ++x; // Incrementing x by 1
        System.out.println("After incrementing, x = " + x);
        --x; // Decrementing x by 1
        System.out.println("After decrementing, x = " + x);
    }
    
}
